def _md_table(df: pd.DataFrame, max_rows: int = 15) -> str:
    if df is None or not len(df):
        return "_no rows_\n"
    df = df.head(max_rows)

    def fmt(v):
        if isinstance(v, (float, np.floating)):
            return "" if not np.isfinite(v) else (f"{v:.4g}")
        return str(v)
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep] + body) + "\n"


def write_report(R: Dict[str, pd.DataFrame], cfg: Config) -> str:
    lines = ["# Bittensor problem sizing — results\n",
             "Generated by `bt_analysis`. Every table below is also saved as CSV in this folder.\n"]
    for title, keys in QUESTIONS:
        lines.append(f"\n## {title}\n")
        for k in keys:
            if k in R:
                lines.append(_md_table(R[k]))
    path = os.path.join(cfg.results_dir, "summary.md")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    return path


def run(cfg: Config, skip_prepare: bool = False, verbose: bool = True) -> Dict[str, pd.DataFrame]:
    t0 = time.time()
    os.makedirs(cfg.results_dir, exist_ok=True)
    if not skip_prepare or not os.path.exists(os.path.join(cfg.processed_dir, "meta.json")):
        if verbose:
            print("[1/4] preparing raw snapshots")
        prepare(cfg, verbose=verbose)
    ds = Dataset(cfg)
    R: Dict[str, pd.DataFrame] = {}
    R.update(run_checks(ds))

    if verbose:
        print(f"[2/4] per-subnet analyses on {len(ds.netuids)} subnets")
    parts = defaultdict(list)
    panels = []
    for sd in ds:
        panel, ex = compute_subnet(sd, cfg)
        panels.append(panel)
        b1_out = b1.per_subnet(sd, panel, cfg)
        b2_out = b2.per_subnet(sd, panel, cfg)
        mech = b2_out["b2_subnets"]["mechanism_type"].iloc[0]
        b3_rows = b3.build_rows(sd, panel, cfg, mech, b1_out["b1_members"])
        for mod_out in (a1.per_subnet(sd, panel, cfg), a3.per_subnet(sd, panel, ex, cfg),
                        a5.per_subnet(sd, panel, cfg), a2.per_subnet(sd, panel, cfg),
                        b1_out, b2_out, {"_b3_rows": b3_rows}):
            for k, v in mod_out.items():
                parts[k].append(v)
        if verbose:
            print(f"  netuid {sd.netuid} done")
    panel = pd.concat(panels, ignore_index=True)
    R["panel"] = panel
    for k, v in parts.items():
        v = [x for x in v if len(x)]
        R[k] = pd.concat(v, ignore_index=True) if v else pd.DataFrame()

    if verbose:
        print("[3/4] cross-subnet aggregation")
    R.update(a1.aggregate(R, cfg))
    R.update(a3.aggregate(R, cfg))
    R.update(a5.aggregate(R, panel, cfg))
    R.update(a2.aggregate(R, panel, cfg))
    R.update(a4.run(panel, R, ds.meta, cfg))
    R.update(rank(R, cfg))
    if verbose:
        print("  B1-B3 aggregation and prediction models")
    R.update(b1.aggregate(R, cfg))
    R.update(b2.aggregate(R, cfg))
    R.update(b3.run(R.get("_b3_rows"), cfg))
    add_b_evidence(R)

    if verbose:
        print("[4/4] writing results")
    for k, v in R.items():
        if isinstance(v, pd.DataFrame) and not k.startswith("_"):
            v.to_csv(os.path.join(cfg.results_dir, f"{k}.csv"), index=False)
    report = write_report(R, cfg)
    if verbose:
        print(f"done in {time.time() - t0:.0f}s -> {report}")
    return R
